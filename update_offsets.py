"""Regenerate src/sdk/offsets.h from a fresh a2x/cs2-dumper dump.

    python update_offsets.py

Clones deps/cs2-dumper on first run, pulls on later runs, then rewrites the
header. Run it after every CS2 update, then rebuild with build.bat.
"""

import io
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
DUMP = os.path.join(ROOT, "deps", "cs2-dumper")
OUT = os.path.join(DUMP, "output")
HEADER = os.path.join(ROOT, "src", "sdk", "offsets.h")

REPO = "https://github.com/a2x/cs2-dumper.git"

# name in offsets.h -> name in the dump
CLIENT_OFFSETS = [
    "dwEntityList",
    "dwLocalPlayerPawn",
    "dwLocalPlayerController",
    "dwViewMatrix",
    "dwViewAngles",
]

SCHEMA = [
    ("C_BaseEntity", "m_iHealth"),
    ("C_BaseEntity", "m_iTeamNum"),
    ("C_BaseEntity", "m_pGameSceneNode"),
    ("C_BaseEntity", "m_lifeState"),
    ("CGameSceneNode", "m_vecAbsOrigin"),
    ("CBasePlayerController", "m_steamID"),
    ("CCSPlayerController", "m_sSanitizedPlayerName"),
    ("CCSPlayerController", "m_hPlayerPawn"),
    ("CCSPlayerController", "m_bPawnIsAlive"),
    ("CCSPlayerController", "m_iPawnHealth"),
    # bones
    ("CGameSceneNode", "m_bDormant"),
    ("CSkeletonInstance", "m_modelState"),
    # aim
    ("C_BaseModelEntity", "m_vecViewOffset"),
    ("C_CSPlayerPawn", "m_angEyeAngles"),
    ("C_BaseEntity", "m_vecVelocity"),
    ("C_CSPlayerPawn", "m_ArmorValue"),
    ("C_CSPlayerPawn", "m_bIsScoped"),
    # glow / chams
    ("C_BaseModelEntity", "m_Glow"),
    ("CGlowProperty", "m_iGlowType"),
    ("CGlowProperty", "m_nGlowRange"),
    ("CGlowProperty", "m_glowColorOverride"),
    ("CGlowProperty", "m_bFlashing"),
    ("CGlowProperty", "m_bGlowing"),
    ("CGlowProperty", "m_fGlowColor"),
    ("CGlowProperty", "m_iGlowTeam"),
    ("CGlowProperty", "m_nGlowRangeMin"),
    ("CGlowProperty", "m_flGlowTime"),
    ("CGlowProperty", "m_flGlowStartTime"),
    ("CGlowProperty", "m_bEligibleForScreenHighlight"),
]


def sync_dump():
    if os.path.isdir(os.path.join(DUMP, ".git")):
        print("[*] pulling cs2-dumper")
        subprocess.check_call(["git", "-C", DUMP, "pull", "--quiet", "--ff-only"])
    else:
        print("[*] cloning cs2-dumper")
        subprocess.check_call(["git", "clone", "--depth", "1", "--quiet", REPO, DUMP])


def load_json(name):
    with io.open(os.path.join(OUT, name), encoding="utf-8") as f:
        return json.load(f)


def main():
    sync_dump()

    info = load_json("info.json")
    build = info.get("build_number", "?")
    stamp = info.get("timestamp", "?")[:10]
    print("[*] dump build %s (%s)" % (build, stamp))

    raw_off = load_json("offsets.json")["client.dll"]
    classes = load_json("client_dll.json")["client.dll"]["classes"]

    missing = []

    client_vals = {}
    for name in CLIENT_OFFSETS:
        if name in raw_off:
            client_vals[name] = raw_off[name]
        else:
            missing.append(name)

    schema_vals = {}
    for cls, field in SCHEMA:
        fields = classes.get(cls, {}).get("fields", {})
        if field in fields:
            schema_vals[field] = fields[field]
        else:
            missing.append("%s::%s" % (cls, field))

    if missing:
        print("[!] not found in the dump: %s" % ", ".join(missing))
        print("[!] the schema was renamed upstream - fix the tables in this script")
        return 1

    pad_c = max(len(n) for n in client_vals)
    pad_s = max(len(n) for n in schema_vals)

    lines = []
    add = lines.append
    add("#pragma once")
    add("#include <cstdint>")
    add("")
    add("// " + "-" * 73)
    add("// GENERATED by update_offsets.py from a2x/cs2-dumper.")
    add("// CS2 build %s, dump %s. Do not edit by hand - rerun the script." % (build, stamp))
    add("//")
    add("// These are STARTUP DEFAULTS only. resolve::Run() overwrites them at load")
    add("// time with values read from the running game, so a build mismatch fixes")
    add("// itself. They are the fallback for when that resolution fails.")
    add("// " + "-" * 73)
    add("")
    add("namespace offsets {   // client.dll relative")
    add("")
    add("// CS2 build these offsets were generated for. Compared at runtime against")
    add("// the build reported by the game's own steam.inf.")
    add("inline constexpr int kDumpBuild = %s;" % build)
    add("")
    for name in CLIENT_OFFSETS:
        add("inline ptrdiff_t %-*s = 0x%X;" % (pad_c, name, client_vals[name]))
    add("")
    add("} // namespace offsets")
    add("")
    add("namespace schema {")
    add("")
    last_cls = None
    for cls, field in SCHEMA:
        if cls != last_cls:
            if last_cls is not None:
                add("")
            add("// " + cls)
            last_cls = cls
        add("inline ptrdiff_t %-*s = 0x%X;" % (pad_s, field, schema_vals[field]))
    add("")
    add("} // namespace schema")
    add("")
    add("namespace team {")
    add("inline constexpr int Spectator = 1;")
    add("inline constexpr int T         = 2;")
    add("inline constexpr int CT        = 3;")
    add("}")
    add("")

    with io.open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print("[+] wrote %s (%d offsets)" % (HEADER, len(client_vals) + len(schema_vals)))
    print("[*] now run build.bat")
    return 0


if __name__ == "__main__":
    sys.exit(main())
